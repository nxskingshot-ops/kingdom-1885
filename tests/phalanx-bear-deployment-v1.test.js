"use strict";
const assert=require("node:assert/strict");
const {planBear}=require("../src/phalanx-bear-deployment-v1.js");
const lead={capacity:10,ratio:[50,20,30]};
const joiners=Array.from({length:6},()=>({capacity:10,ratio:[0,0,100]}));
const inv={infantry:5,cavalry:2,archers:63};
const ok=planBear({inventory:inv,lead,joiners});
assert.equal(ok.deployments.length,7);
assert.equal(ok.fullyFeasible,true);
assert.deepEqual(ok.remaining,{infantry:0,cavalry:0,archers:0});
assert.equal(ok.deployments[0].role,"lead");
assert.equal(ok.deployments[6].index,6);
assert.equal(ok.timingVerified,false);
const low=planBear({inventory:{infantry:5,cavalry:2,archers:10},lead,joiners});
assert.equal(low.fullyFeasible,false);
assert.equal(low.deficit.archers,53);
assert.ok(low.deployments.some(d=>d.shortfall>0));
const joinerOnly=planBear({inventory:{infantry:0,cavalry:0,archers:10},mode:"joiners-only",joiners:[{capacity:10,ratio:[0,0,100]}]});
assert.equal(joinerOnly.deployments.length,1);
assert.equal(planBear({inventory:{infantry:5,cavalry:2,archers:3},mode:"lead-only",lead}).deployments.length,1);
assert.throws(()=>planBear({inventory:inv,lead,joiners:[...joiners,joiners[0]]}));
assert.throws(()=>planBear({inventory:{infantry:-1,cavalry:0,archers:0},lead}));
for(const d of low.deployments)for(const k of ["infantry","cavalry","archers"])assert.ok(d.assigned[k]<=d.target[k]);
console.log("Bear feasibility checks passed");
