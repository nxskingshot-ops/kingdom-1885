const assert=require("node:assert/strict");
const E=require("../src/phalanx-screenshot-joiner-v2.js");
const j=(name,level=5,playerId=name)=>({name,level,playerId});
const balanced=E.evaluate([j("Chenko"),j("Yeonwoo"),j("Amane"),j("Helga")]);
assert.equal(balanced.grouped,2.25);
assert.equal(balanced.allAdditive,2);
assert.equal(balanced.totals.attack,50);
assert.equal(balanced.totals.lethality,50);
const mixed=E.evaluate([j("Chenko"),j("Yeonwoo"),j("Amane"),j("Hilde")]);
assert.ok(Math.abs(mixed.grouped-2.1)<1e-12);
assert.equal(mixed.totals.defense,10);
assert.equal(E.skill("Saul",5).health,15);
assert.equal(E.skill("Helga",5).attack,25);
assert.throws(()=>E.skill("Amane",6));
assert.throws(()=>E.evaluate([j("Chenko")]));
const pool=[j("Chenko"),j("Yeonwoo"),j("Amane"),j("Helga"),j("Hilde")];
assert.equal(E.optimize(pool).evaluated,5);
assert.equal(E.optimize(pool).top[0].result.grouped,2.25);
console.log("12 PHALANX screenshot joiner regression assertions passed");
