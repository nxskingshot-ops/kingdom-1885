"use strict";
const assert=require("node:assert/strict");
const v=require("../src/phalanx-personal-profile-validation-v1.js");
assert.equal(v.validateAccountTier("basic").ok,true);
assert.equal(v.validateAccountTier("full").ok,true);
assert.equal(v.validateAccountTier("admin").ok,false);
assert.equal(v.validatePlayerLookup({playerId:"000123"}).value.playerId,"000123");
for(const bad of ["","-1","1 OR 1=1","123abc",123, "1".repeat(21)])assert.equal(v.validatePlayerLookup({playerId:bad}).ok,false);
const inventory={infantry:10,cavalry:20,archers:30};
assert.equal(v.validateTroopInventory(inventory).ok,true);
for(const bad of [-1,NaN,Infinity,1.2,"100",Number.MAX_SAFE_INTEGER+1])assert.equal(v.validateTroopInventory({...inventory,archers:bad}).ok,false);
assert.equal(v.validateMarches([{capacity:100,ratio:[50,20,30]}]).ok,true);
for(const ratio of [[0,0,0],[1,2],[1,-1,3],[NaN,1,2],[Infinity,1,2]])assert.equal(v.validateMarches([{capacity:100,ratio}]).ok,false);
const profile={ownerId:"u1",verified:true,inventory,marches:[{capacity:100,ratio:[50,20,30]}]};
assert.equal(v.validateConfirmedProfile(profile,"u1").ok,true);
assert.equal(v.validateConfirmedProfile(profile,"u2").ok,false);
assert.equal(v.validateConfirmedProfile({...profile,verified:false},"u1").ok,false);
assert.equal(v.validateConfirmedProfile({...profile,inventory:{...inventory,archers:-1}},"u1").ok,false);
console.log("PHALANX profile validation tests passed");
